#!/usr/bin/env python3
"""Generates lookup tables so the board never calls cosf/sinf per sample.

Measured on the STM32 (Release, -Os): each cosf costs about 175 cycles, and the
features called cos/sin about 6,000 times per frame. These values never change,
so they are computed once here (in double precision, rounded to float once)
and stored in flash.

Writes core/include/laennec/tables.h:
  LAENNEC_HANN_1024[1024]  Hann window for the spectrum   0.5 - 0.5*cos(2*pi*i/1024)
  LAENNEC_HANN_960[960]    Hann window for the envelope   0.5 - 0.5*cos(2*pi*i/960)
  LAENNEC_TWIDDLE_COS[512] cos(2*pi*k/1024)  for the FFT
  LAENNEC_TWIDDLE_SIN[512] sin(2*pi*k/1024)

Usage:  python3 tools/gen_tables.py
"""
import numpy as np

N = 1024
VALID = N - 65 + 1  # envelope samples kept after the 65-tap FIR (see features.c)
PATH = "core/include/laennec/tables.h"


def c_array(name, values):
    lines = [f"static const float {name}[{len(values)}] = {{"]
    for i in range(0, len(values), 6):
        lines.append("    " + " ".join(f"{np.float32(v):.9e}f," for v in values[i:i + 6]))
    lines.append("};")
    return lines


def hann(length):
    return 0.5 - 0.5 * np.cos(2 * np.pi * np.arange(length) / length)


k = np.arange(N // 2)
out = [
    "/* Generated by tools/gen_tables.py. Do not edit by hand. */",
    "#ifndef LAENNEC_TABLES_H",
    "#define LAENNEC_TABLES_H",
    "",
    f"#define LAENNEC_TABLE_FFT_SIZE {N}",
    f"#define LAENNEC_ENV_VALID {VALID}",
    "",
]
out += c_array(f"LAENNEC_HANN_{N}", hann(N)) + [""]
out += c_array(f"LAENNEC_HANN_{VALID}", hann(VALID)) + [""]
out += c_array("LAENNEC_TWIDDLE_COS", np.cos(2 * np.pi * k / N)) + [""]
out += c_array("LAENNEC_TWIDDLE_SIN", np.sin(2 * np.pi * k / N)) + [""]
out += ["#endif /* LAENNEC_TABLES_H */", ""]
open(PATH, "w").write("\n".join(out))
print(f"wrote {PATH}: {N} + {VALID} window values, {N // 2} twiddles "
      f"({(N + VALID + N) * 4 / 1024:.1f} KB of flash)")
