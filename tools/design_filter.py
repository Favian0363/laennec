#!/usr/bin/env python3
"""Designs the band-pass filter used before envelope analysis and writes it as
a C header: core/include/laennec/bandpass_coeffs.h

Why a band-pass: each time a ball rolls over a defect, the bearing "rings" at
a high resonant frequency, like a tapped bell. Keeping only 2-5 kHz throws away
the slow shaking of the shaft and keeps the ringing.

Usage:  python3 tools/design_filter.py
"""
from scipy.signal import firwin, freqz

FS = 12000
NUM_TAPS = 65            # odd: every frequency is delayed by exactly 32 samples
BAND_HZ = (2000, 5000)

taps = firwin(NUM_TAPS, BAND_HZ, pass_zero=False, fs=FS)
# A linear-phase FIR is symmetric: taps[k] == taps[NUM_TAPS-1-k]. features.c
# relies on this to "fold" the filter (33 multiplies instead of 65), so make it
# exact, including after rounding to float.
taps = (taps + taps[::-1]) / 2
f32 = taps.astype("float32")
assert (f32 == f32[::-1]).all(), "taps must be exactly symmetric for the folded FIR"
check_hz = [0, 500, 1000, 1500, 3500, 5500]
_, response = freqz(taps, worN=check_hz, fs=FS)

lines = [
    "/* Generated by tools/design_filter.py. Do not edit by hand. */",
    "#ifndef LAENNEC_BANDPASS_COEFFS_H",
    "#define LAENNEC_BANDPASS_COEFFS_H",
    "",
    f"/* FIR band-pass {BAND_HZ[0]}-{BAND_HZ[1]} Hz at {FS} Hz, {NUM_TAPS} taps (scipy firwin, Hamming window).",
    " * Gain: " + ", ".join(f"{f} Hz = {abs(h):.4f}" for f, h in zip(check_hz, response)) + " */",
    f"#define LAENNEC_BANDPASS_TAPS {NUM_TAPS}",
    "",
    "/* Deliberately NOT const: a non-const array with initial values goes in the",
    " * .data section, which the startup code copies into RAM at boot. The FIR reads",
    " * these 65 values for every output sample; measured on the STM32, reading them",
    " * from flash (wait states at 170 MHz) made the filter 34% slower.",
    " * Exactly symmetric: LAENNEC_BANDPASS[k] == LAENNEC_BANDPASS[TAPS-1-k]. */",
    "static float LAENNEC_BANDPASS[LAENNEC_BANDPASS_TAPS] = {",
]
for i in range(0, NUM_TAPS, 4):
    lines.append("    " + " ".join(f"{t:.9e}f," for t in taps[i:i + 4]))
lines += ["};", "", "#endif /* LAENNEC_BANDPASS_COEFFS_H */", ""]

path = "core/include/laennec/bandpass_coeffs.h"
with open(path, "w") as f:
    f.write("\n".join(lines))
print(f"wrote {path}")
for f, h in zip(check_hz, response):
    print(f"  gain at {f:5d} Hz: {abs(h):.4f}")
