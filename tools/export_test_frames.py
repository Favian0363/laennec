#!/usr/bin/env python3
"""Exports real CWRU frames as a C header, so the board can run the exact
same features + classifier on them and compare with the PC.

Picks PER_CLASS frames from each condition at the 3 hp load (never seen in
training), spread evenly through each recording. For each frame it stores:
  - the 1024 raw samples,
  - the true class and Python's predicted class,
  - the 11 features the PC computed (from data/features.csv, made by the
    same C code), so the board can check its own features against them.

Usage:  python3 tools/export_test_frames.py [per_class=4]
Writes: firmware/Core/Inc/laennec_test_frames.h  (generated: not committed)
"""
import csv
import sys

import numpy as np

CLASSES = ["normal", "inner", "ball", "outer"]  # same order as the C enum
NAMES = ["log_rms", "kurtosis", "crest", "centroid_khz", "band_0_1k", "band_1_2k5",
         "band_2k5_4k", "band_4k_6k", "env_outer", "env_ball", "env_inner"]
N = 1024
TEST_LOAD = 3
OUT = "firmware/Core/Inc/laennec_test_frames.h"


def main():
    per_class = int(sys.argv[1]) if len(sys.argv) > 1 else 4
    if not 1 <= per_class <= 20:
        sys.exit("per_class must be 1..20 (each frame takes 4 KB of the board's 512 KB flash)")

    manifest = list(csv.DictReader(open("data/prepared/manifest.csv")))
    features = {(int(r["file"]), int(r["frame"])): [float(r[n]) for n in NAMES]
                for r in csv.DictReader(open("data/features.csv"))}
    predicted = {(int(r["file"]), int(r["frame"])): int(r["predicted"])
                 for r in csv.DictReader(open("data/predictions.csv"))}

    frames = []
    for condition in CLASSES:
        rec = next(r for r in manifest if r["condition"] == condition and int(r["load_hp"]) == TEST_LOAD)
        file = int(rec["file"])
        samples = np.fromfile(rec["path"], dtype="<f4")
        count = len(samples) // N
        for k in np.linspace(0, count - 1, per_class).round().astype(int):
            frames.append({"file": file, "frame": int(k), "truth": CLASSES.index(condition),
                           "expected": predicted[(file, int(k))], "features": features[(file, int(k))],
                           "samples": samples[k * N:(k + 1) * N]})

    f32 = lambda v: f"{np.float32(v):.9e}f"
    lines = [
        "/* Generated by tools/export_test_frames.py. Do not edit or commit. */",
        "#ifndef LAENNEC_TEST_FRAMES_H",
        "#define LAENNEC_TEST_FRAMES_H",
        "",
        '#include "laennec/features.h"',
        "",
        f"#define LAENNEC_TEST_FRAME_COUNT {len(frames)}",
        "",
        "typedef struct {",
        "    short file;          /* CWRU file number */",
        "    short frame;         /* frame index inside that recording */",
        "    signed char truth;   /* true class */",
        "    signed char expected;/* class Python predicted */",
        "    float pc_features[LAENNEC_NUM_FEATURES]; /* what the PC computed */",
        "    float samples[LAENNEC_FRAME_LEN];",
        "} laennec_test_frame;",
        "",
        f"/* {len(frames)} frames from the {TEST_LOAD} hp load, which the model never saw in training. */",
        "static const laennec_test_frame LAENNEC_TEST_FRAMES[LAENNEC_TEST_FRAME_COUNT] = {",
    ]
    for fr in frames:
        lines.append(f"  {{ {fr['file']}, {fr['frame']}, {fr['truth']}, {fr['expected']},")
        lines.append("    {" + ", ".join(f32(v) for v in fr["features"]) + "},")
        lines.append("    {")
        for i in range(0, N, 6):
            lines.append("      " + ", ".join(f32(v) for v in fr["samples"][i:i + 6]) + ",")
        lines.append("    } },")
    lines += ["};", "", "#endif /* LAENNEC_TEST_FRAMES_H */", ""]
    open(OUT, "w").write("\n".join(lines))
    print(f"wrote {OUT}: {len(frames)} frames ({per_class} per class, {TEST_LOAD} hp load), "
          f"about {len(frames) * 4.1:.0f} KB of flash")


if __name__ == "__main__":
    main()
